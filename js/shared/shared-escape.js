/**
 * Minimal HTML escaping for safe interpolation into innerHTML/template strings.
 * Use this for any untrusted string coming from DB/API/user input.
 */
export function escapeHtml(value) {
  if (value === null || value === undefined) return '';
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}


